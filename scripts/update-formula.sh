#!/usr/bin/env bash
# Generate Formula/orka.rb from the signed checksums of an Orka release.
#
# Usage: scripts/update-formula.sh <version>   (for example v0.3.0)
#
# Requires gh (authenticated), cosign, and curl. The checksum file must carry a
# keyless Cosign signature from Orka's release workflow on the matching
# release-X.Y branch at the tagged commit; anything else stops the update.
set -euo pipefail

readonly repository=orka-agents/orka
readonly formula=Formula/orka.rb

version=${1:?usage: update-formula.sh <version>}
if [[ ! ${version} =~ ^v(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)$ ]]; then
  echo "Only stable versions such as v1.2.3 are published to the tap: ${version}" >&2
  exit 1
fi
branch="release-${BASH_REMATCH[1]}.${BASH_REMATCH[2]}"

work=$(mktemp -d)
trap 'rm -rf "${work}"' EXIT

checksums="orka_${version}_checksums.txt"
base_url="https://github.com/${repository}/releases/download/${version}"
curl -fsSL -o "${work}/${checksums}" "${base_url}/${checksums}"
curl -fsSL -o "${work}/${checksums}.bundle" "${base_url}/${checksums}.bundle"

commit=$(gh api "repos/${repository}/commits/${version}" --jq .sha)
cosign verify-blob --bundle "${work}/${checksums}.bundle" \
  --certificate-identity "https://github.com/${repository}/.github/workflows/release.yml@refs/heads/${branch}" \
  --certificate-oidc-issuer https://token.actions.githubusercontent.com \
  --certificate-github-workflow-sha "${commit}" \
  "${work}/${checksums}"

sha() {
  local archive="orka_${version}_$1.tar.gz" digest
  digest=$(awk -v name="${archive}" '$2 == name { print $1 }' "${work}/${checksums}")
  if [[ ! ${digest} =~ ^[0-9a-f]{64}$ ]]; then
    echo "No checksum for ${archive} in ${checksums}" >&2
    return 1
  fi
  printf '%s' "${digest}"
}

darwin_arm64=$(sha darwin_arm64)
darwin_amd64=$(sha darwin_amd64)
linux_arm64=$(sha linux_arm64)
linux_amd64=$(sha linux_amd64)

mkdir -p "$(dirname "${formula}")"
cat >"${formula}" <<FORMULA
# Generated by scripts/update-formula.sh from the signed ${version} release checksums. Do not edit.
class Orka < Formula
  desc "CLI for Orka, the Kubernetes-native task execution platform"
  homepage "https://github.com/${repository}"
  license "MIT"

  on_macos do
    on_arm do
      url "${base_url}/orka_${version}_darwin_arm64.tar.gz"
      sha256 "${darwin_arm64}"
    end
    on_intel do
      url "${base_url}/orka_${version}_darwin_amd64.tar.gz"
      sha256 "${darwin_amd64}"
    end
  end

  on_linux do
    on_arm do
      url "${base_url}/orka_${version}_linux_arm64.tar.gz"
      sha256 "${linux_arm64}"
    end
    on_intel do
      url "${base_url}/orka_${version}_linux_amd64.tar.gz"
      sha256 "${linux_amd64}"
    end
  end

  def install
    bin.install "orka"
    generate_completions_from_executable(bin/"orka", "completion")
  end

  test do
    assert_equal "orka v#{version}", shell_output("#{bin}/orka version").strip
  end
end
FORMULA
echo "Wrote ${formula} for ${version}"
